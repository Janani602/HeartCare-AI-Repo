# --- HELPER FUNCTIONS ---
@st.cache_resource
def load_model():
    try:
        with open("heart_disease_model.pkl", "rb") as f:
            return pickle.load(f)
    except Exception as e:
        return None

@st.cache_data
def load_data():
    try:
        return pd.read_csv("heart_disease.csv")
    except:
        return None

def generate_pdf(patient_data, prediction, risk_level):
    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Arial", 'B', 16)
    pdf.cell(200, 10, txt="HeartCare AI - Medical Diagnosis Report", ln=True, align='C')
    
    pdf.set_font("Arial", size=12)
    pdf.cell(200, 10, txt=f"Report Date: {datetime.date.today()}", ln=True, align='R')
    
    pdf.ln(10)
    pdf.set_font("Arial", 'B', 14)
    pdf.cell(200, 10, txt="Patient Profile", ln=True)
    
    pdf.set_font("Arial", size=11)
    for key, value in patient_data.items():
        pdf.cell(100, 8, txt=f"{key}: {value}", ln=True)
        
    pdf.ln(10)
    pdf.set_font("Arial", 'B', 14)
    pdf.cell(200, 10, txt="Diagnosis Result", ln=True)
    
    pdf.set_font("Arial", 'B', 12)
    color = (255, 75, 75) if risk_level == "HIGH" else (46, 204, 113)
    pdf.set_text_color(*color)
    pdf.cell(200, 10, txt=f"Risk Level: {risk_level}", ln=True)
    pdf.cell(200, 10, txt=f"Probability: {prediction:.1%}", ln=True)
    
    pdf.set_text_color(0, 0, 0)
    pdf.ln(5)
    pdf.set_font("Arial", 'B', 10)
    pdf.multi_cell(0, 5, txt="IMPORTANT MEDICAL DISCLAIMER: This tool is for educational purposes and not a medical diagnosis. This report is generated by an AI model and must be reviewed by a qualified healthcare professional.")
    
    return bytes(pdf.output(dest='S'))

